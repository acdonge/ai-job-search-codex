#!/usr/bin/env python3
"""Register shared .agents skills with Claude Code using small regular files.

Run with --check in CI to detect missing, stale, or extra managed adapters.
Normal mode updates only managed SKILL.md files; unrelated user skills and
supporting files are left alone. Requires the existing PyYAML dev dependency.
"""

import argparse
import json
from pathlib import Path
import re
import sys

try:
    import yaml
except ImportError:
    sys.exit("sync_claude_skills.py requires PyYAML: pip install pyyaml")


ROOT = Path(__file__).resolve().parents[1]
MARKER = "<!-- Generated by tools/sync_claude_skills.py. -->"


def render_adapter(source: Path) -> str:
    text = source.read_text(encoding="utf-8")
    frontmatter = re.match(r"\A---\n(.*?)\n---(?:\n|$)", text, re.DOTALL)
    if not frontmatter:
        raise ValueError(f"{source}: missing YAML frontmatter")
    data = yaml.safe_load(frontmatter.group(1))
    if not isinstance(data, dict):
        raise ValueError(f"{source}: frontmatter must be a mapping")
    for key in ("name", "description"):
        if not isinstance(data.get(key), str) or not data[key].strip():
            raise ValueError(f"{source}: {key} must be a nonempty string")
    # JSON string literals are YAML scalars too; preserve quoted/folded metadata
    # without carrying runtime-specific permission fields into the adapter.
    header = "\n".join(f"{key}: {json.dumps(data[key], ensure_ascii=False)}"
                       for key in ("name", "description"))
    canonical = f".agents/skills/{source.parent.name}/SKILL.md"
    return (
        f"---\n{header}\n---\n\n{MARKER}\n\n"
        f"Read and follow the [shared skill](../../../{canonical}) at\n"
        f"`{canonical}` before doing any work.\n\n"
        "Resolve sibling reference files relative to that canonical skill directory;\n"
        "resolve repository paths from the repository root. Run shared commands from\n"
        "the repository root. Use the current runtime's available tools and permission\n"
        "model, following the shared runtime guidance.\n\n"
        "Edit the canonical skill, then run `python3 tools/sync_claude_skills.py`\n"
        "from the repository root to refresh this registration.\n"
    )


def ensure_regular_target(path: Path, root: Path) -> None:
    for candidate in (path, *path.parents):
        if candidate == root:
            break
        if candidate.is_symlink():
            raise ValueError(f"refusing symlink target: {candidate.relative_to(root)}")
    if path.exists() and not path.is_file():
        raise ValueError(f"target is not a regular file: {path.relative_to(root)}")


def synchronize(root: Path, check: bool) -> int:
    sources = sorted(root.glob(".agents/skills/*/SKILL.md"))
    if not sources:
        raise ValueError("no canonical skills found under .agents/skills; nothing changed")
    targets = {
        root / ".claude/skills" / source.parent.name / "SKILL.md": render_adapter(source)
        for source in sources
    }
    changes: list[tuple[str, Path, str]] = []
    for path, expected in targets.items():
        ensure_regular_target(path, root)
        if not path.exists():
            changes.append(("missing", path, expected))
            continue
        actual = path.read_text(encoding="utf-8")
        if MARKER not in actual.splitlines():
            raise ValueError(f"unmanaged adapter would be overwritten: {path.relative_to(root)}")
        if actual != expected:
            changes.append(("stale", path, expected))
    for path in sorted(root.glob(".claude/skills/*/SKILL.md")):
        # Never follow unrelated user symlinks or descend into supporting files.
        if path in targets or any(p.is_symlink() for p in (path, *path.parents)):
            continue
        if path.is_file() and MARKER in path.read_text(encoding="utf-8").splitlines():
            changes.append(("extra", path, ""))
    # Build and validate the entire plan before changing any files.
    for status, path, expected in changes:
        print(f"{status}: {path.relative_to(root).as_posix()}")
        if not check:
            if status == "extra":
                path.unlink()  # Leave its directory and any user-owned siblings intact.
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected, encoding="utf-8")
    if check and changes:
        print("Run python3 tools/sync_claude_skills.py to refresh managed adapters.")
        return 1
    print(f"sync_claude_skills: OK ({len(targets)} shared skills)")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report drift without changing files")
    parser.add_argument("--root", type=Path, default=ROOT, help="repository root (default: this checkout)")
    args = parser.parse_args(argv)
    try:
        return synchronize(args.root.resolve(), args.check)
    except (OSError, ValueError, yaml.YAMLError) as exc:
        print(f"sync_claude_skills: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
